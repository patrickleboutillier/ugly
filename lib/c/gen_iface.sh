#!/bin/bash
#
# Generates ugly_iface.h, the plugin vtable, from the UGLY_IFACE lines of the
# API header given as $1 (ugly_api.h). Output goes to stdout.

api="${1:?usage: gen_iface.sh path/to/ugly_api.h}"

echo "/* Generated by gen_iface.sh from ugly_api.h. Do not edit. */"
echo
echo "struct _ugly_interface {"
cat "$api" | while read tag rtype func args ; do
	if [ "$tag" = "UGLY_IFACE_V" ] ; then
		rtype='void*'
		tag=UGLY_IFACE
	fi
	if [ "$tag" = "UGLY_IFACE" ] ; then
		name=${func#ugly_}
		echo "    $rtype (*$name)$args"
	fi
done
echo "} ;"
echo 


echo "#define UGLY_INIT_IFACE(iface, lang) \\"
echo "    (ugly_interface *)malloc(sizeof(ugly_interface)) ; \\"
cat "$api" | while read tag rtype func args ; do
	if [ "$tag" = "UGLY_IFACE_V" ] ; then
		rtype='void*'
		tag=UGLY_IFACE
	fi
	if [ "$tag" = "UGLY_IFACE" ] ; then
		name=${func#ugly_}
		echo "    $rtype _ugly_ ## lang ## _$name$args \\"
		echo "    iface->$name = _ugly_ ## lang ## _$name ; \\"
	fi
done
echo 

